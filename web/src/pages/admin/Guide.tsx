/**
 * The whole dashboard explained in Bangla, on one page, for a shop owner who
 * has never used an admin panel. Every button name is kept in English inside
 * brackets, because the buttons themselves are in English — a translated name
 * the owner cannot find on screen would be worse than no translation.
 */

interface Section {
  id: string;
  icon: string;
  title: string;
  body: JSX.Element;
}

/** A labelled table for "field → what it does" explanations. */
function Fields({ rows }: { rows: [string, string][] }) {
  return (
    <div className="table-scroll">
      <table className="data">
        <thead>
          <tr>
            <th style={{ width: '34%' }}>ঘর (Field)</th>
            <th>কী কাজ করে</th>
          </tr>
        </thead>
        <tbody>
          {rows.map(([field, meaning]) => (
            <tr key={field}>
              <td>
                <strong>{field}</strong>
              </td>
              <td>{meaning}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** Numbered walkthrough — the format the owner will actually follow. */
function Steps({ items }: { items: string[] }) {
  return (
    <ol className="guide-steps">
      {items.map((step, i) => (
        <li key={i}>{step}</li>
      ))}
    </ol>
  );
}

function Note({ tone = 'info', children }: { tone?: 'info' | 'warn'; children: React.ReactNode }) {
  return <div className={`alert ${tone}`}>{children}</div>;
}

